"""Generate src/pagedata.s (FAIR KNIGHT page text, tables, presets). usage: mkdata.py"""
import os
def s(name,text,w=None):
    if w: assert len(text)<=w,(name,text); text=text.ljust(w)
    for ch in text: assert ch==' ' or (ch.isalnum() and ch.isupper() or ch.isdigit()), (name,ch)
    return f'{name}: .byte "{text}",$FF\n'
L='; generated by tools/mkdata.py\n'
L+=s('s_title','FAIR KNIGHT OPTIONS')
L+=s('s_hint','X FOR FAIR KNIGHT OPTIONS',26)
L+=s('s_help1','LEFT RIGHT CHANGE  A RESET',26)
L+=s('s_help2','START RETURNS',26)
labels=['PRESET','KNOCKBACK','CHEST HINTS','ENHANCED','BETTER ARMOR','WEAPON','EXIT']
for i,t in enumerate(labels): L+=s(f'l{i}',t,14)
