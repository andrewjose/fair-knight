#!/usr/bin/env python3
"""Small two-pass SM83 (Game Boy) assembler for Fair Knight GBC patches.

Opcode templates are generated by inverting sm83dis.py, so the accepted syntax is exactly
what the disassembler prints, e.g.  ld a, [$C0E0]   ldh [$FF40], a   jr nz, label   ld [hl+], a
Directives:  .org BANK:ADDR   .db expr,...   .dw expr,...   .ds n[,fill]   NAME = expr   label:
Expressions are Python expressions over labels/constants ($hex and %bin literals allowed;
lo(x)/hi(x) helpers).  ';' starts a comment.
Output: list of (file_offset, bytes) chunks; callers write them into a ROM with byte asserts.
"""
import re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from sm83dis import dis

def _templates():
    T = {}
    def add(text, op, kind):
        key = re.sub(r'\s+', ' ', text.strip().lower())
        T.setdefault(key, (op, kind))
    for op in range(256):
        if op == 0xCB:
            for o in range(256):
                ln, t = dis(bytes([0xCB, o, 0]), 0)
                add(t, bytes([0xCB, o]), None)
            continue
        ln, t = dis(bytes([op, 0xAB, 0xCD]), 0)
        if t.startswith('db '): continue
        if ln == 1: add(t, bytes([op]), None)
        elif ln == 3: add(t.replace('$CDAB', '{nn}'), bytes([op]), 'nn')
        elif ln == 2:
            if t.startswith('jr '):   # target = 0+2+(0xAB signed) = -83 -> $FFAD
                add(t.replace('$FFAD', '{rel}'), bytes([op]), 'rel')
            elif '$FFAB' in t: add(t.replace('$FFAB', '{hn}'), bytes([op]), 'hn')
            elif 'sp' in t and ('-85' in t): add(t.replace('-85', '{e}').replace('sp+{e}', 'sp{e}'), bytes([op]), 'e')
            elif t == 'stop': add(t, bytes([0x10, 0]), None)
            else: add(t.replace('$AB', '{n}'), bytes([op]), 'n')
    return T
TEMPL = _templates()
PATTERNS = []
for k, (op, kind) in TEMPL.items():
    rx = re.escape(k)
    for ph in ('\\{nn\\}', '\\{n\\}', '\\{rel\\}', '\\{hn\\}', '\\{e\\}'):
        rx = rx.replace(ph, '(.+)')
    PATTERNS.append((re.compile('^' + rx + '$'), op, kind, k))
# prefer literal (no-operand) matches first, then those with fewer wildcards
PATTERNS.sort(key=lambda p: (p[2] is not None, -len(p[3])))

def conv(expr):
    expr = re.sub(r'\$([0-9A-Fa-f]+)', lambda m: '0x' + m.group(1), expr)
    expr = re.sub(r'%([01]+)', lambda m: '0b' + m.group(1), expr)
    return expr

class Asm:
    def __init__(s): s.sym = {}; s.chunks = []
    def ev(s, e, final):
        env = dict(s.sym); env['lo'] = lambda x: x & 0xFF; env['hi'] = lambda x: (x >> 8) & 0xFF
        try: return eval(conv(e), {'__builtins__': {}}, env)
        except NameError:
            if final: raise
            return 0
    def assemble(s, text, name='<src>'):
        lines = text.splitlines()
        for final in (False, True):
            bank = None; pc = None; out = []; cur = None; scope = '_'
            for no, raw in enumerate(lines, 1):
                line = raw.split(';', 1)[0].rstrip()
                if not line.strip(): continue
                g = re.match(r'^([A-Za-z_][\w]*):', line.strip())
                if g: scope = g.group(1)
                line = re.sub(r'@(\w+)', lambda m: scope + '__' + m.group(1), line)
                try:
                    m = re.match(r'^([A-Za-z_.][\w.]*):\s*(.*)$', line.strip())
                    if m and not re.match(r'^\w+\s*=', line.strip()):
                        lab = m.group(1)
                        if not final:
                            if lab in s.sym and s.sym[lab] != pc and not lab.startswith('@'): raise ValueError('dup label ' + lab)
                        s.sym[lab] = pc; line = m.group(2)
                        if not line.strip(): continue
                    st = line.strip()
                    m = re.match(r'^([A-Za-z_]\w*)\s*=\s*(.+)$', st)
                    if m: s.sym[m.group(1)] = s.ev(m.group(2), final); continue
                    if st.lower().startswith('.org'):
                        b, a = st[4:].strip().split(':'); bank = s.ev(b, True); pc = s.ev(a, True)
                        cur = [bank, pc, bytearray()]; out.append(cur); continue
                    if st.lower().startswith('.db'):
                        for e in split_args(st[3:]):
                            if e.strip().startswith('"'):
                                for ch in e.strip()[1:-1]: cur[2].append(CHARMAP[ch])
                            else: cur[2].append(s.ev(e, final) & 0xFF)
                        pc = cur[1] + len(cur[2]); continue
                    if st.lower().startswith('.dw'):
                        for e in split_args(st[3:]):
                            v = s.ev(e, final) & 0xFFFF; cur[2] += bytes([v & 0xFF, v >> 8])
                        pc = cur[1] + len(cur[2]); continue
                    if st.lower().startswith('.ds'):
                        a = split_args(st[3:]); n = s.ev(a[0], True); f = s.ev(a[1], True) if len(a) > 1 else 0
                        cur[2] += bytes([f]) * n; pc = cur[1] + len(cur[2]); continue
                    cur[2] += s.ins(st, pc, final); pc = cur[1] + len(cur[2])
                except Exception as ex:
                    raise SystemExit(f'{name}:{no}: {raw.strip()}  -> {ex}')
        s.chunks += [(b, a, bytes(d)) for b, a, d in out]
        return s
    def ins(s, st, pc, final):
        t = re.sub(r'\s+', ' ', st.strip())
        tl = t.lower()
        for rx, op, kind, k in PATTERNS:
            m = rx.match(tl)
            if not m: continue
            if kind is None: return op
            # operand text from the original-case string
            mo = rx.match(tl); start, end = mo.span(1); e = t[start:end]
            if kind in ('nn',):
                if re.fullmatch(r'[abcdehl]|bc|de|hl|sp|af|\[.*', e.strip().lower()): continue
                v = s.ev(e, final); return op + bytes([v & 0xFF, (v >> 8) & 0xFF])
            if kind == 'n':
                if re.fullmatch(r'[abcdehl]|bc|de|hl|sp|af|\[.*\]', e.strip().lower()): continue
                v = s.ev(e, final); return op + bytes([v & 0xFF])
            if kind == 'hn':
                v = s.ev(e, final); return op + bytes([v & 0xFF])
            if kind == 'e':
                v = s.ev(e, final); return op + bytes([v & 0xFF])
            if kind == 'rel':
                v = s.ev(e, final); d = v - (pc + 2)
                if final and not -128 <= d <= 127: raise ValueError('jr out of range')
                return op + bytes([d & 0xFF])
        raise ValueError('unknown instruction')

def split_args(a):
    out, cur, q = [], '', False
    for ch in a:
        if ch == '"': q = not q
        if ch == ',' and not q: out.append(cur); cur = ''
        else: cur += ch
    if cur.strip(): out.append(cur)
    return out

# Game font: digits $00-$09, A-Z $0A-$23, space $FF (same as the NES game)
CHARMAP = {str(i): i for i in range(10)}
CHARMAP.update({chr(65 + i): 0x0A + i for i in range(26)}); CHARMAP[' '] = 0xFF

def file_off(bank, addr):
    return addr if addr < 0x4000 else bank * 0x4000 + (addr - 0x4000)

if __name__ == '__main__':
    # self-test: assemble every template back and compare with the disassembler
    bad = 0
    for k, (op, kind) in TEMPL.items():
        if kind is None:
            a = Asm(); b = a.ins(k, 0, True)
            if b != op: bad += 1; print('mismatch', k, b.hex(), op.hex())
    print('templates', len(TEMPL), 'no-operand mismatches', bad)
    a = Asm().assemble('.org 0:$100\nstart: ld a, $12\n ld hl, $C0E0\n ldh [$FF40], a\n jr nz, start\n call $0841\n ld a, [$C0E0]\n ld [hl+], a\n bit 6, a\n jp hl\n ld [$C5C1], a\n add hl, bc\n cp $02\n .db "FAIR KNIGHT", 0\n')
    print(a.chunks[0][2].hex(' '))
    print('\n'.join(__import__('sm83dis').listing(b'\x00'*0x100 + a.chunks[0][2] + b'\x00'*8, 0, 0x100, 11)))
