"""Extract GBC Ghosts'n Goblins hidden-item records (stage-list type $1A, template $7C1B) into a CSV.
usage: secrets_extract.py gng.gbc out.csv [out.asm]   (out.asm = the sec_tab/sec_nm block pasted into src/fk.asm)
Stage list locations (pointer $C228/9 in bank [$C201] at stage start, found with PyBoy) are tabled below.
Each $1A record's 6-byte list entry: type, flags, X block, Y block, param ptr (bank 1) -> 10-byte record:
  [obj template $7C1B][item template][1A 00][trigger X block, trigger Y block?][reveal handler $46xx]."""
import sys, csv
LISTS = {1: (0x6558, 10), 2: (0x53D0, 11), 3: (0x54E0, 13), 4: (0x5982, 15), 5: (0x6EDE, 16), 6: (0x6290, 17)}
# reveal handler -> (kind, harmful, name index). Handler $46xx calls the item spawner 1:$45D0 with a descriptor
# whose collect routine decides the effect: $4697 score +$0100, $46C7 score +$0050, $46B6 time +1:00,
# $46D8 lives+1, $46E6 -> $06FB armor back on, $46A8 -> $CB00=1 frog curse (harmful), $49A7+7w weapons.
KIND = {0x4691: ('money', 0, 0), 0x46C1: ('coins', 0, 1), 0x46B0: ('clock (time +1:00)', 0, 2), 0x46D2: ('1UP', 0, 3),
        0x46E0: ('armor', 0, 4), 0x46A2: ('frog curse', 1, 5), 0x46EE: ('lance', 0, 6), 0x46F4: ('dagger', 0, 7),
        0x46FA: ('torch', 0, 8), 0x4700: ('axe', 0, 9), 0x4706: ('cross', 0, 10)}
NAMES = ['MONEY', 'COINS', 'CLOCK', '1UP', 'ARMOR', 'FROG', 'LANCE', 'KNIFE', 'TORCH', 'AXE', 'CROSS']
def b36(t): return ', '.join('$%02X' % (0xFF if c == ' ' else int(c) if c.isdigit() else 10 + ord(c) - 65) for c in t)
def asm(rows):
    out = ['; ---- secrets table (generated by tools/secrets_extract.py; trigger X block, Y block, id = (param-$79CD)/10, name index|$80 harmful)',
           'sec_tab:.dw sec_s1, sec_s2, sec_s3, sec_s4, sec_s5, sec_s6, sec_none']
    for st in LISTS:
        out.append(f'sec_s{st}:')
        for r in rows:
            if r['stage'] == st:
                pid = (int(r['param'][1:], 16) - 0x79CD) // 10
                out.append(f"        .db ${r['x'] // 16:02X}, ${r['y'] // 16:02X}, ${pid:02X}, ${r['name_idx'] | (0x80 if r['harmful'] else 0):02X}")
        out.append('        .db $FF')
    out.append('sec_none:.db $FF')
    out.append('; item names, READY-screen font (0-9, A-Z = $0A-$23, space $FF), 6 chars each')
    out.append('sec_nm: .db ' + b36(''.join(n.ljust(6) for n in NAMES)))
    out.append('s_secr: .db ' + b36('SECRETS '))
    out.append('s_of:   .db ' + b36(' OF '))
    return '\n'.join(out) + '\n'

def rd(d, bank, a): return d[bank * 0x4000 + a - 0x4000] if a >= 0x4000 else d[a]
def main(rom, out):
    d = open(rom, 'rb').read(); rows = []
    for st, (a, b) in LISTS.items():
        sec = i = 0
        while True:
            t = rd(d, b, a)
            if t == 0xFF: break
            if t == 0xFE: sec += 1; a += 6; i += 1; continue
            r = [rd(d, b, a + k) for k in range(6)]
            if t == 0x1A:
                p = r[4] | r[5] << 8; raw = bytes(rd(d, 1, p + k) for k in range(10))
                tpl = raw[0] | raw[1] << 8; h = raw[8] | raw[9] << 8
                if tpl == 0x7C1B:
                    k, harm, ni = KIND.get(h, ('?', 0, 0))
                    rows.append(dict(stage=st, section=sec, index=i, x=r[2] * 16, y=r[3] * 16, param=f'${p:04X}',
                                     item_tpl=f'${raw[2] | raw[3] << 8:04X}', b6=raw[6], b7=raw[7],
                                     handler=f'${h:04X}', kind=k, harmful=harm, name_idx=ni, raw=raw.hex(' ').upper()))
            a += 6; i += 1
    with open(out, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    for st in LISTS: print('stage', st, sum(r['stage'] == st for r in rows))
    return rows
if __name__ == '__main__':
    rows = main(sys.argv[1], sys.argv[2])
    if len(sys.argv) > 3: open(sys.argv[3], 'w').write(asm(rows))
