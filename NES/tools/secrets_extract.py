#!/usr/bin/env python3
"""Extract Ghosts'n Goblins (USA, NES) stage event lists and the hidden items (event/object type $11).
Event list per section $C2: pointer table at $8038 in the stage-data bank; 8-byte entries:
 [0] trigger position (X page; Y high byte in vertical sections >= $0B), [1] param (item kind for $20),
 [2] event type (handler $D5FB[type]; also the object type $0631 for spawners), [3] X lo, [4] X page,
 [5] Y lo, [6] Y hi, [7] initial $04F0 flags. A list ends at a $80 trigger byte.
usage: secrets_extract.py ROM [CSV]"""
import sys, csv
rom=open(sys.argv[1],'rb').read()[16:]
BANK_OF={**{s:1 for s in range(7)},**{s:2 for s in range(7,11)},11:3,12:3,13:3}   # $C8 observed per section
SECTION=['1A','1B','1C','2A','2B','2C','2D','3A','3B','4A','4B','5','6','7']
STAGE=[1,1,1,2,2,2,2,3,3,4,4,5,6,7]
KIND={0:'treasure 0',1:'treasure 1',2:'treasure 2',3:'treasure 3',4:'1UP',5:'armor',6:'torch',7:'axe',8:'dagger',9:'cross',10:'lance',11:'kind 11',12:'time down',13:'time up'}
HARMFUL={12}   # time down
def rd(b,a): return rom[b*0x4000+a-0x8000]
def events(sec):
    b=BANK_OF[sec]; p=rd(b,0x8038+2*sec)|rd(b,0x8039+2*sec)<<8
    out=[]; i=0
    while True:
        e=[rd(b,p+8*i+k) for k in range(8)]
        if e[0]==0x80 or i>200: break
        out.append((i,p+8*i,e)); i+=1
    return b,p,out
def triggers():
    rows=[]
    for sec in range(14):
        b,p,ev=events(sec)
        for i,a,e in ev:
            if e[2]==0x11:
                rows.append(dict(section=sec,name=SECTION[sec],stage=STAGE[sec],index=i,bank=b,addr=f'${a:04X}',
                    trigger=e[0],kind=e[1],kind_name=KIND.get(e[1],f'kind {e[1]}'),harmful=int(e[1] in HARMFUL),
                    x=e[4]*256+e[3],y=e[6]*256+e[5],flags=f'${e[7]:02X}',duck=int(e[7]&1),raw=' '.join(f'{v:02X}' for v in e)))
    return rows
if __name__=='__main__':
    rows=triggers()
    for r in rows: print(r)
    if len(sys.argv)>2:
        with open(sys.argv[2],'w',newline='') as f:
            w=csv.DictWriter(f,fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    import collections; print(collections.Counter(r['stage'] for r in rows))

def write_inc(rows, path):
    """Assembly include for bank2.s: per-secret section / X lo / X hi, and the count per stage 1-6."""
    rows=[r for r in rows if r['stage']<=6]
    cnt=[sum(1 for r in rows if r['stage']==s) for s in range(1,7)]
    L=['; generated by tools/secrets_extract.py - hidden items (event/object type $11), in stage order',
       f'NSEC = {len(rows)}',
       'sec_s:  .byte '+','.join(str(r['section']) for r in rows),
       'sec_xl: .byte '+','.join(f'${r["x"]&0xFF:02X}' for r in rows),
       'sec_xh: .byte '+','.join(f'${r["x"]>>8:02X}' for r in rows),
       'sec_yh: .byte '+','.join(f'${r["y"]>>8:02X}' for r in rows),
       'st_cnt: .byte '+','.join(str(c) for c in cnt)]
    open(path,'w').write('\n'.join(L)+'\n')
if __name__=='__main__' and len(sys.argv)>3:
    write_inc(triggers(), sys.argv[3])
